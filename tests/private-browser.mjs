import assert from 'node:assert/strict';
import fs from 'node:fs';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
const base=process.env.MTANALOG_BROWSER_URL||'http://127.0.0.1:8790';
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_EXECUTABLE,args:['--no-sandbox']});
const errors=[];
try{
 const guest=await browser.newContext(),gp=await guest.newPage();gp.on('pageerror',e=>errors.push(e.message));
 await gp.goto(base);await gp.locator('#loading').waitFor({state:'hidden'});
 assert.equal(await gp.locator('#private-panel').count(),0);
 for(const endpoint of ['pairs','catalog','chart?symbol=ETHBTC'])assert.equal((await guest.request.get(base+'/api/private/'+endpoint)).status(),403);
 for(const endpoint of ['start','delete','settings'])assert.equal((await guest.request.post(base+'/api/private/'+endpoint,{data:{symbol:'ETHBTC'}})).status(),403);
 const owner=await browser.newContext(),page=await owner.newPage();page.on('pageerror',e=>errors.push(e.message));
 const link=fs.readFileSync(process.env.MTANALOG_OWNER_LINK_FILE,'utf8').trim();
 await page.goto(base+'/private'+new URL(link).hash);await page.locator('#private-start').waitFor({state:'visible'});
 await page.waitForFunction(()=>document.querySelector('#private-start')?.disabled===false,{},{timeout:25000});
 assert.equal(new URL(page.url()).hash,'');
 const cookie=(await owner.cookies()).find(c=>c.name==='__Host-firecharts-private');assert.ok(cookie?.secure&&cookie.httpOnly&&cookie.sameSite==='Strict');
 const ownerHeaders={Cookie:'__Host-firecharts-private='+cookie.value};
 const before=(await(await owner.request.get(base+'/api/private/pairs',{headers:ownerHeaders})).json()).pairs;
 assert.equal(before.length,0,'Live test requires no existing personal collections; never touch owner data');
 await page.locator('#private-symbol').fill('ETHBTC');await page.locator('#private-start').click();
 await page.waitForFunction(()=>document.querySelector('#base-asset').textContent==='ETH');
 assert.equal(await page.locator('#quote-asset').innerText(),'BTC');
 assert.equal(await page.locator('[data-period="1w"]').isVisible(),false);
 await page.waitForFunction(()=>document.querySelector('#last-price').textContent!=='—',{},{timeout:60000});
 const data=await(await owner.request.get(base+'/api/private/chart?symbol=ETHBTC',{headers:ownerHeaders})).json();assert.equal(data.quote_asset,'BTC');assert.equal(data.private_pair,true);
 assert.equal(data.window_hours,6);assert.ok(data.rows>0);assert.ok(data.high<1);assert.ok(data.liquidity.some(c=>c?.some(([,v])=>v>0)));
 await page.locator('#price-step').fill('0.0001');await page.locator('#price-margin').fill('4');await page.locator('#apply-price').click();
 await page.waitForFunction(()=>document.querySelector('#price-range').textContent==='±4%');
 await page.locator('[data-filter="manual"]').click();await page.locator('#manual-low').fill('0.001');await page.locator('#manual-high').fill('0.1');
 await page.waitForTimeout(1300);
 await page.screenshot({path:'output/private-desktop.png',fullPage:true});
 await page.reload();await page.waitForFunction(()=>document.querySelector('#private-start')?.disabled===false);
 await page.getByRole('button',{name:'Открыть',exact:true}).first().click();
 assert.equal(await page.locator('#price-step').inputValue(),'0.0001');assert.equal(await page.locator('#manual-low').inputValue(),'0.001');
 const mobile=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 await mobile.addCookies(await owner.cookies());const mp=await mobile.newPage();mp.on('pageerror',e=>errors.push(e.message));
 await mp.goto(base+'/private');await mp.waitForFunction(()=>document.querySelector('#private-start')?.disabled===false);
 await mp.getByRole('button',{name:'Открыть',exact:true}).first().click();await mp.locator('#loading').waitFor({state:'hidden'});
 assert.ok(await mp.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));await mp.screenshot({path:'output/private-mobile.png',fullPage:true});
 const bad=await owner.request.post(base+'/api/private/delete',{headers:{...ownerHeaders,Origin:base},data:{symbol:'BTCUSDT'}});assert.equal(bad.status(),400);
 await page.getByRole('button',{name:'Остановить и удалить',exact:true}).first().click();
 await page.waitForFunction(()=>document.querySelectorAll('.private-pair').length===0,{},{timeout:65000});
 assert.equal(await page.locator('#base-asset').innerText(),'BTC');
 const removed=await owner.request.get(base+'/api/private/chart?symbol=ETHBTC',{headers:ownerHeaders});assert.equal(removed.status(),400);
 assert.equal((await guest.request.get(base+'/api/chart')).status(),200);
 assert.deepEqual(errors,[]);await owner.close();await guest.close();await mobile.close();
 console.log('Private checks passed: guest API403, secure owner session, ETHBTC live precision/quote/chart, settings across reload, mobile layout, BTC protected, stop/delete and public BTC preserved.');
}catch(e){console.error(String(e.stack||e).replace(/#key=[A-Za-z0-9_-]+/g,'#key=[redacted]'));process.exitCode=1;}
finally{await browser.close();}
